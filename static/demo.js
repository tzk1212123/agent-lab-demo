// Demo panel (left): pick a plan (from a paper link / existing plan) → pick executor (human / robot arm) → tidy bench (stow unused, place needed)
// → run with step-by-step highlighting (steps on the left ↔ equipment on the bench) → conclusion and labour saved.
// Depends on: studio.js (S, $, esc, api, fmt, fmtT, reset, startPolling, setView), bench.js (SB, sbApi, sbPoll, startSandbox, toast),
//       fx.js (SKILL_TEXT), focus.js (FOCUS).
"use strict";

const DEMO = { choice: null, prep: null, running: false, current: 0, done: false, summaryShown: false };

const CMD_TEXT = {
  set_temperature: (p) => `Set temperature ${p.temperature} °C`, heater_on: () => "Heater on", heater_off: () => "Heater off",
  set_speed: (p) => `Set speed ${p.speed} rpm`, stir_on: () => "Stir on", stir_off: () => "Stir off",
  dispense: (p) => `Dispense ${p.volume} mL (${p.rate} mL/min)`, infuse: (p) => `Infuse ${p.volume} mL`, withdraw: (p) => `Withdraw ${p.volume} mL`,
  refill: () => "Refill", stop: () => "Stop", read: () => "Read", measure: () => "Measure", start: () => "Start",
  sparge: (p) => `Sparge foam ${p.flow_mL_min} mL/min × ${p.duration_s} s`, stir: (p) => `Stir foam ${p.speed_rpm} rpm × ${p.duration_s} s`,
  record: (p) => `Record video ${Math.round(p.duration_s / 60)} min`, drain: () => "Drain", rinse: () => "Rinse",
  set_wavelength: (p) => `Set wavelength ${p.wavelength} nm`, inject: () => "Inject", run: () => "Run",
};
function stepText(st, labels) {
  const L = (id) => labels[id] || id;
  switch (st.kind) {
    case "task": {
      const f = typeof SKILL_TEXT !== "undefined" && SKILL_TEXT[st.skill];
      return f ? f(st.params || {}, L) : `${st.skill} (${Object.entries(st.params || {}).map(([k, v]) => `${k}=${v}`).join(", ")})`;
    }
    case "command": {
      const f = CMD_TEXT[st.command];
      return `${st.device}: ${f ? f(st.params || {}) : st.command}`;
    }
    case "wait": return `Wait ${fmtT(st.seconds)}`;
    case "wait_until": return `Wait until ${st.condition?.ref} ${st.condition?.op} ${st.condition?.value}`;
    case "wait_stable": return `Wait for ${st.ref} to stabilise`;
    case "record": return `Record readings: ${(st.refs || []).join(", ")}`;
    case "repeat_until": return `Repeat ${(st.body || []).length} sub-steps until ${st.condition?.ref} ${st.condition?.op} ${st.condition?.value}`;
    default: return st.kind;
  }
}

// ---------------------------------------------------------------- pick a plan
async function demoInit() {                         // the left panel only handles imports: paper-generated plan / manual plan
  const ex = await api("/api/experiments");
  for (const b of document.querySelectorAll("#demoTabs button")) b.onclick = () => {
    for (const x of document.querySelectorAll("#demoTabs button")) x.classList.toggle("on", x === b);
    $("demoPaper").hidden = b.dataset.k !== "paper"; $("demoManual").hidden = b.dataset.k !== "manual";
  };
  $("demoAnalyze").onclick = demoAnalyzePaper;
  if (typeof prepInit === "function") {             // prep library: defaults to the first demo (four-pump colour mixing)
    prepInit(ex);
    const s = (ex.showcase || [])[0], e = s && ex.experiments.find((x) => x.id === s.id);
    if (s && !DEMO.choice) prepSelect({ kind: "experiment", ref: s.id, title: e ? e.title : s.id });
  }
  $("demoUrl").addEventListener("keydown", (e) => { if (e.key === "Enter") demoAnalyzePaper(); });
}
function demoChoiceShow() {
  const c = DEMO.choice;
  $("demoChoice").innerHTML = c ? `<div class="demo-chosen">Plan: <b>${esc(c.title)}</b>${c.kind === "paper" ? `<span class="muted"> (generated by LLM from a paper${c.planning_s ? `, took ${Math.round(c.planning_s)} s` : ""})</span>` : c.kind === "manual" ? `<span class="muted"> (filled in by a human, checked and dry-run)</span>` : `<span class="muted"> (existing fixed procedure)</span>`}</div>` : "";
  if (typeof prepSync === "function") prepSync();
  if (typeof updateRunBtn === "function") updateRunBtn();
}
function demoAnalyzePaper() {                        // open the "Generate plan" page (genplan.js) to watch the LLM read and think
  const url = $("demoUrl").value.trim();
  if (!url) return toast("Paste a paper link (or DOI) first", true);
  genOpen(url);
}
function demoPaperDone(r) {                           // "Use this plan" clicked on the plan generation page
  const m = r.check.missing, miss = m.instruments + m.steps + m.reactions + m.materials;
  $("demoPaperOut").innerHTML = `<div class="pc-verdict ${miss ? "warn" : "good"}">${esc(r.check.verdict)}</div>
    <div class="muted">Plan ${r.plan_steps} steps · missing instruments ${m.instruments} · operations ${m.steps} · reactions ${m.reactions} · reagents ${m.materials}</div>`;
  DEMO.choice = { kind: "paper", ref: r.exp_id, title: r.title, planning_s: r.source?.llm_s };
  demoChoiceShow();
}

// ---------------------------------------------------------------- start: tidy bench → run
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function demoStart(opts = {}) {             // opts: {robot, speed} (from the right panel / Quick start; otherwise the left panel's choices)
  const c = DEMO.choice; if (!c) return;
  const robot = opts.robot ?? !!$("selRobot").value;
  $("demoResult").innerHTML = ""; DEMO.done = false; DEMO.summaryShown = false;
  try {
    const prep = await api("/api/demo/prepare", { kind: c.kind, ref: c.ref, plan: c.plan || null });
    DEMO.prep = prep; DEMO.current = 0; DEMO.t0 = null;
    demoRenderSteps();
    $("demoPhase").textContent = "Tidying bench: stowing unused equipment, placing what's needed…";
    // 1) load experiment → 2) clear the bench, place devices one by one by docking relations
    const L = prep.layout;
    await api("/api/sandbox/new", { sid: "studio", experiment: prep.experiment, humans: 1 });   // (online demo: recorded bench states)
    SB.sid = "studio"; await startSandbox();
    await sbApi("stow_all", { keep_slots: L.container_slots, bench: L.bench }); await sbPoll();   // first stow everything on the equipment table
    if (typeof gearTransfer === "function") {      // transition: highlight needed items on the equipment page → fly to the bench
      $("demoPhase").textContent = `Fetching ${L.used_devices.length} needed devices from the equipment table…`;
      await gearTransfer(L.used_devices, prep.title);
    }
    $("demoPhase").textContent = "Placing and assembling on the bench by docking relations…";
    await demoOrganize(prep, 550);
    $("demoPhase").textContent = `Bench ready: ${Object.keys(L.device_slots).length} devices and ${L.container_slots.length} container slots on the bench, ${L.stored.length} devices on the shelf. Starting…`;
    await sleep(900);
    // 3) run (same layout)
    const speed = opts.speed ?? $("selSpeed").value, layout = { ...L };
    setView("front");                                    // experiment start: switch to front view to watch
    const extra = { plan: prep.plan, assembly_steps: prep.assembly_steps || 0 };   // one-off assembly moved to the front (fast-forwarded before the run)
    if (c.kind === "paper") await api("/api/paper/run", { exp_id: c.ref, layout, robot: robot ? "xarm6_standard" : "", speed, planning_s: c.planning_s || "", ...extra });
    else await api("/api/live/start", { experiment: c.ref, planner: "fixed", layout, robot: robot ? "xarm6_standard" : "", speed, humans: 1, ...extra });
    if (typeof toggleDrawer === "function") toggleDrawer(false);
    reset("live"); startPolling();
    DEMO.running = true;
    $("demoPhase").textContent = robot ? "Running: robot arm executes; humans only do steps it can't" : "Running: manual execution";
    if (typeof FOCUS !== "undefined") { FOCUS.auto = true; FOCUS.key = null; }
  } catch (e) {
    $("demoPhase").textContent = ""; toast(e.message, true); $("demoResult").innerHTML = `<div class="pc-bad">${esc(e.message)}</div>`;
  } finally { if (typeof updateRunBtn === "function") updateRunBtn(); }
}

// Tidy bench: all devices back to the shelf, needed container slots stay at the bench front, then place them one by one per the layout (docking relations). delay = interval per item (ms, 0 = instant)
async function demoOrganize(prep, delay) {
  const L = prep.layout;
  await sbApi("stow_all", { keep_slots: L.container_slots, bench: L.bench }); await sbPoll();
  if (typeof FOCUS !== "undefined") FOCUS.auto = false;
  if (delay) { setView("top"); $("fit").click(); await sleep(700); }
  for (const [did, sid] of Object.entries(L.device_slots)) {
    const g = L.slots[sid];
    try { await sbApi("move_device", { id: did, x_mm: g.x_mm, y_mm: g.y_mm, rotation: L.rotations[did] || 0, floor: (L.floor || []).includes(did) }); }
    catch (e) { toast(`${did}: ${e.message}`, true); }
    if (delay) { await sbPoll(); demoHighlight([did]); await sleep(delay); }
  }
  for (const sid of L.container_slots) {
    const g = L.slots[sid]; if (!g) continue;
    try { await sbApi("move_slot", { slot: sid, x_mm: g.x_mm, y_mm: g.y_mm }); } catch (e) { toast(`${sid}: ${e.message}`, true); }
    if (delay) { await sbPoll(); await sleep(delay * 0.6); }
  }
  await sbPoll();
  if (typeof FOCUS !== "undefined") FOCUS.auto = true;
}
// when the sidebar / top bar loads an experiment: also place only what's needed (experiments without a plan are placed as-is)
async function demoOrganizeFor(experiment) {
  const paper = experiment.startsWith("generated/");
  try {
    const prep = await api("/api/demo/prepare", { kind: paper ? "paper" : "experiment", ref: paper ? experiment.slice(10) : experiment });
    await demoOrganize(prep, 0);
    return prep;
  } catch (e) { return null; }
}

// ---------------------------------------------------------------- step list and equipment highlighting
function demoRenderSteps() {
  const p = DEMO.prep; if (!p) return;
  const n = p.assembly_steps || 0;
  $("demoSteps").innerHTML = p.steps.map((s) => (n && s.index === 1 ? `<li class="ds-sec">Assembly (set up before the run, once)</li>` : "")
      + (n && s.index === n + 1 ? `<li class="ds-sec">Run</li>` : "")
      + `<li data-i="${s.index}" data-t="${esc(s.targets.join(" "))}" class="${s.assembly ? "asm" : ""}">
      <span class="ds-n">${s.index}</span><span class="ds-t">${esc(stepText(s.step, p.labels))}</span></li>`).join("");
  for (const li of $("demoSteps").querySelectorAll("li[data-i]")) {
    li.onmouseenter = () => demoHighlight((li.dataset.t || "").split(" ").filter(Boolean), +li.dataset.i);
    li.onmouseleave = () => demoHighlight(DEMO.targets || []);
  }
}
function demoHighlight(ids, n) {
  for (const x of document.querySelectorAll("#world .demo-hl")) x.classList.remove("demo-hl");
  for (const x of document.querySelectorAll("#world .demo-badge")) x.remove();
  for (const id of ids) {
    for (const node of document.querySelectorAll(`#world [data-d="${CSS.escape(id)}"]:not(.stored-dev), #world [data-c="${CSS.escape(id)}"]`)) {
      node.classList.add("demo-hl");
      if (n) {                                     // step numbers next to equipment (matching the list on the left)
        const b = node.getBBox();
        const t = el("g", { class: "demo-badge" }, node);
        el("circle", { cx: b.x + b.width, cy: b.y, r: Math.max(16, Math.min(40, b.width * 0.18)) }, t);
        el("text", { x: b.x + b.width, y: b.y + Math.max(6, Math.min(14, b.width * 0.06)), "font-size": Math.max(16, Math.min(36, b.width * 0.16)) }, t, String(n));
      }
    }
  }
}
// called after each redraw: find the current step (latest plan_step event), update the list and bench highlights; conclude at the end
function demoTick(f, p) {
  if (!DEMO.prep || S.mode !== "live" || !f) return;
  let cur = 0;
  for (const e of S.events) if (e.type === "plan_step" && e.seq < f.event_seq) cur = e.index;
  const items = $("demoSteps").querySelectorAll("li[data-i]");
  items.forEach((li) => {
    const i = +li.dataset.i;
    li.classList.toggle("done", i < cur || (DEMO.done && i <= cur));
    li.classList.toggle("cur", i === cur && !DEMO.done);
  });
  if (cur !== DEMO.current) {
    DEMO.current = cur;
    const li = $("demoSteps").querySelector(`li[data-i="${cur}"]`);
    if (li) li.scrollIntoView({ block: "nearest", behavior: "smooth" });
  }
  const st = DEMO.prep.steps.find((s) => s.index === cur);
  DEMO.targets = st ? st.targets : [];
  demoHighlight(DEMO.targets, cur);
  renderProgress(f, cur);
}
// translucent plan progress bar on the right: step n of N, current step, next step, elapsed time
function renderProgress(f, cur) {
  const box = $("planProg"), p = DEMO.prep;
  if (!p || !f) { box.hidden = true; return; }
  const n = p.steps.length, done = DEMO.done ? n : Math.max(0, cur - 1);
  if (DEMO.t0 == null) DEMO.t0 = f.t;
  const pct = Math.round(100 * (DEMO.done ? 1 : (done + (cur ? 0.5 : 0)) / Math.max(1, n)));
  const st = p.steps.find((s) => s.index === cur), nx = p.steps.find((s) => s.index === cur + 1);
  box.hidden = false;
  box.innerHTML = `<div class="pp-title">${esc(p.title)}</div>
    <div class="pp-bar"><div style="width:${pct}%"></div></div>
    <div class="pp-row"><span>${DEMO.done ? "Done" : `${p.assembly_steps && cur <= p.assembly_steps ? "Assembling · " : (p.assembly_steps ? "Running · " : "")}Step ${cur || 0} / ${n}`}</span><span>${pct}%</span></div>
    ${!DEMO.done && st ? `<div class="pp-cur">▶ ${esc(stepText(st.step, p.labels))}</div>` : ""}
    ${!DEMO.done && nx ? `<div class="pp-next">Next: ${esc(stepText(nx.step, p.labels))}</div>` : ""}
    <div class="pp-row muted"><span>Elapsed ${fmtT(Math.max(0, f.t - DEMO.t0))}</span><span>${esc($("selSpeed")?.value || "1")}× speed</span></div>
    ${DEMO.done || DEMO.skipHinted ? "" : `<div class="pp-row muted"><span>Enter skips this step</span></div>`}`;
}
function demoFinish(p) {
  if (!DEMO.prep || DEMO.summaryShown || !p || p.status === "running") return;
  DEMO.done = true; DEMO.summaryShown = true; DEMO.running = false;
  const sc = p.score || {}, sm = p.summary || {}, sub = p.submitted;
  const min = (s) => s == null ? "—" : s >= 3600 ? `${(s / 3600).toFixed(1)} h` : `${(s / 60).toFixed(1)} min`;
  let concl = "";
  if (p.status === "stopped") concl = `<div class="pc-bad">Experiment aborted</div>`;
  else if (p.status === "error") concl = `<div class="pc-bad">Error: ${esc(p.error || "")}</div>`;
  else if (sub) concl = `<div class="demo-big">${esc(sub.quantity)} = <b>${fmt(sub.value, 4)} ${esc(sub.unit)}</b></div>
      <div class="muted">${esc((sub.method || "").slice(0, 160))}</div>
      ${sc.truth != null ? `<div class="${sc.pass ? "pc-good" : "pc-bad"}">${sc.pass ? "✓ Matches truth" : "✗ Doesn't match truth"}: truth ${fmt(sc.truth, 4)}${sc.rel_error != null ? ` (deviation ${(sc.rel_error * 100).toFixed(1)} %)` : ""}</div>` : ""}`;
  else concl = `<div class="muted">Plan finished but no conclusion was submitted${sc.why ? `: ${esc(sc.why)}` : ""}</div>`;
  const plan = sm.planning;
  $("demoResult").innerHTML = `<h4>Conclusion</h4>${concl}
    <h4>Labour saved</h4>
    <table class="demo-tbl">
      <tr><td>Experiment time (simulated)</td><td>${min(sm.sim_time_s)}</td></tr>
      <tr><td>Hands-on time if fully manual</td><td>${min(sm.all_manual_hands_on_s)}</td></tr>
      ${sm.assembly_steps ? `<tr><td>Pre-run assembly (human, once)</td><td>${min(sm.assembly_hands_on_s)}</td></tr>` : ""}
      <tr><td>${sm.assembly_steps ? "Human hands-on during run" : "Actual human hands-on"}</td><td>${min(sm.human_hands_on_s)}</td></tr>
      <tr><td>Done by robot arm</td><td>${min(sm.robot_s)}</td></tr>
      <tr class="hl"><td>Hands-on time saved</td><td>${min(sm.saved_hands_on_s)}</td></tr>
      ${plan ? `<tr><td>Human reads paper, writes plan (est.)</td><td>${min(plan.human_estimate_s)}</td></tr>
      <tr><td>LLM reads paper, writes plan</td><td>${plan.llm_s != null ? min(plan.llm_s) : "—"}</td></tr>
      <tr class="hl"><td>Planning time saved</td><td>${min(plan.saved_s)}</td></tr>` : ""}
    </table>
    <div class="muted demo-assume">${(sm.assumptions || []).map(esc).join("<br>")}</div>`;
  $("demoPhase").textContent = "Demo finished";
  renderProgress(S.frames[S.idx], DEMO.current);
  $("demoResult").scrollIntoView({ block: "nearest", behavior: "smooth" });
}

function toggleDemo() {                                  // wide window: show / hide; narrow window (≤ 980 px): open / close the drawer
  const narrow = window.matchMedia("(max-width: 980px)").matches;
  if (narrow) document.body.classList.toggle("demo-open");
  else document.body.classList.toggle("demo-hidden");
  setTimeout(() => $("fit").click(), 30);
}
document.addEventListener("keydown", (e) => {          // ← key: toggle the left demo panel; Enter: fast-forward the current step
  if (!$("pfModal").hidden) { if (e.key === "Escape") $("pfModal").hidden = true; return; }   // table editor open: don't steal keys
  if (["INPUT", "SELECT", "TEXTAREA", "BUTTON"].includes(document.activeElement?.tagName)) return;
  if (e.key === "ArrowLeft") { e.preventDefault(); toggleDemo(); }
  else if (e.key === "Enter" && S.mode === "live" && S.status === "running") {
    e.preventDefault();
    api("/api/live/skip", {}).then(() => {                 // show the hint only the first time so it doesn't block the view
      if (!DEMO.skipHinted) { DEMO.skipHinted = true; toast("Fast-forwarded this step (still executed, just without waiting real time)"); }
    }).catch(() => {});
  }
});
$("demoHandle").onclick = toggleDemo;
