// Agent console for a running experiment (bottom-left of the stage, translucent): what it is thinking / controlling / which parameters it changed.
// All data comes from the run log: plan_step (current step), decision (each control-loop verdict), command / task_started (controls issued),
// agent_thought (model reasoning when the DeepSeek agent plans live). Who wrote the plan (LLM / human / program) is shown in the title.
"use strict";

const CON = { open: true };

function conFmtParams(p) {
  return Object.entries(p || {}).map(([k, v]) => `${k}=${typeof v === "number" ? +v.toFixed(4) : v}`).join(", ");
}
function conSource() {
  const k = DEMO.choice?.kind, pl = typeof S !== "undefined" ? $("selPlanner")?.value : "";
  if (k === "paper") return "Plan: generated by LLM (DeepSeek) from a paper";
  if (k === "manual") return "Plan: filled in by a human";
  if (pl && pl !== "fixed" && !DEMO.prep) return "Plan: DeepSeek agent plans as it goes";
  return "Plan: fixed procedure (programmed)";
}

// current step + latest verdict → one line of "what it is thinking"
function conThought(st, dec, labels) {
  if (!st) return "Waiting to start…";
  const L = (x) => labels?.[x] || x;
  const cond = (d) => `${d.ref} = ${d.value == null ? "(no reading yet)" : +(+d.value).toFixed(4)}${d.unit ? " " + d.unit : ""}, target ${d.op} ${d.target}`;
  let t;
  switch (st.kind) {
    case "repeat_until":
      t = dec ? (dec.verdict === "met" ? `${cond(dec)} → reached, ending loop` : `${cond(dec)} → not yet, another round (round ${(dec.iteration ?? 0) + 1})`)
        : `Preparing loop until ${st.condition?.ref} ${st.condition?.op} ${st.condition?.value}`;
      break;
    case "wait_until":
      t = dec && dec.verdict === "met" ? `${cond(dec)} → condition met, moving on` : `Watching ${st.condition?.ref} until ${st.condition?.op} ${st.condition?.value}`;
      break;
    case "wait": t = `Wait ${st.seconds} s for mixing / reaction / readings to settle`; break;
    case "wait_stable": t = `Wait for ${st.ref} to stabilise (change ≤ ${st.tolerance} within ${st.window_s} s)`; break;
    case "record": t = `Read and record: ${(st.refs || []).join(", ")}${st.label ? ` (${st.label})` : ""}`; break;
    case "command": t = `${st.device} runs ${st.command}${Object.keys(st.params || {}).length ? ` (${conFmtParams(st.params)})` : ""}`; break;
    case "task": t = `Operation: ${st.skill} (${Object.entries(st.params || {}).map(([k, v]) => `${k}=${L(v)}`).join(", ")})`; break;
    default: t = st.kind;
  }
  const why = st.note || st.text;
  return why ? `${t}\nReason: ${why}` : t;
}

function renderConsole(f) {
  const box = $("agentConsole"); if (!box) return;
  const live = S.mode === "live" || (S.mode === "replay" && DEMO.prep);
  if (!live || !f) { box.hidden = true; return; }
  box.hidden = false;
  const evs = S.events.filter((e) => e.seq < (f.event_seq ?? Infinity));
  let cur = 0, dec = null, thought = null;
  const ctl = [], params = [], last = {};
  for (const e of evs) {
    if (e.type === "plan_step") { cur = e.index; dec = null; }
    else if (e.type === "decision") dec = e;
    else if (e.type === "agent_thought") thought = e;
    else if (e.type === "command") {
      ctl.push({ t: e.t, text: `${e.device}.${e.command}(${conFmtParams(e.params)})` });
      const setter = /^set_/.test(e.command);              // parameter change: a set_* command, or a parameter differing from last time for the same command (e.g. new flow rate)
      for (const [k, v] of Object.entries(e.params || {})) {
        const key = setter ? `${e.device}.${k}` : `${e.device}.${e.command}.${k}`;
        if ((setter || key in last) && last[key] !== v) params.push({ t: e.t, key, from: last[key], to: v });
        last[key] = v;
      }
    } else if (e.type === "task_started") ctl.push({ t: e.t, text: `${e.executor}: ${e.skill}(${conFmtParams(e.params)})` });
  }
  const steps = DEMO.prep?.steps || [];
  const st = steps.find((s) => s.index === cur)?.step;
  const llm = !DEMO.prep && $("selPlanner")?.value !== "fixed";
  const lastTool = [...evs].reverse().find((e) => e.type === "agent_tool_call");
  const think = llm && !thought ? (lastTool ? `Calling ${lastTool.tool}…` : "DeepSeek is reading the task and planning the first step (shown after each round of thinking; may take tens of seconds)")
    : thought && !DEMO.prep
    ? `${thought.content || ""}${thought.reasoning ? `\n…${thought.reasoning.slice(-400)}` : ""}${thought.tools?.length ? `\n→ calls ${thought.tools.join(", ")}` : ""}`
    : conThought(st, dec, DEMO.prep?.labels);
  let state = "";                                         // formerly the top narration: who is doing what, what each device is doing
  if (typeof narrate === "function") {
    const { lines, dev } = narrate(f);
    const l = lines[0];
    state = [l ? `<b>${esc(l.who)}</b> is ${esc(l.txt)}${l.left > 1 ? ` (about ${fmt(l.left, 2)} s left)` : ""}` : "", ...dev.slice(0, 3).map(esc)]
      .filter(Boolean).join("<br>");
  }
  const tt = (t) => `<span class="ct">${fmtT(t)} </span>`;
  box.innerHTML = `<div class="con-head"><b>Agent console</b><span class="muted">${esc(conSource())}</span><button class="con-x" title="Collapse / expand">${CON.open ? "–" : "+"}</button></div>
    ${CON.open ? `<div class="con-sec"><i>${llm ? "🧠 LLM thinking" : "⚙ Runner deciding"}</i><div class="con-think">${esc(think)}</div></div>
    ${state ? `<div class="con-sec"><i>📍 Status</i><div class="con-state">${state}</div></div>` : ""}
    <div class="con-sec"><i>🎛 Controls</i>${ctl.slice(-3).reverse().map((c) => `<div>${tt(c.t)}${esc(c.text)}</div>`).join("") || `<div class="muted">—</div>`}</div>
    <div class="con-sec"><i>🔧 Parameters</i>${params.slice(-4).reverse().map((p) => `<div>${tt(p.t)}<b>${esc(p.key)}</b> ${p.from === undefined ? "set to" : `${esc(String(p.from))} →`} <b>${esc(String(p.to))}</b></div>`).join("") || `<div class="muted">—</div>`}</div>` : ""}`;
  box.querySelector(".con-x").onclick = () => { CON.open = !CON.open; renderConsole(f); };
}
